# ---------------- SEVERITY BASED DOSAGE ----------------
def severity_based_dosage(severity):

    if severity < 30:
        return "Low", "1 ml per Liter"

    elif 30 <= severity < 60:
        return "Moderate", "2 ml per Liter"

    elif 60 <= severity < 80:
        return "High", "3 ml per Liter"

    else:
        return "Critical", "4 ml per Liter"


# ---------------- FINAL RECOMMENDATION ----------------
def pesticide_recommendation(disease, severity):

    if "healthy" in disease.lower():
        return "None", "0 ml", "Healthy Crop"

    pesticide = get_base_pesticide(disease)
    level, dosage = severity_based_dosage(severity)

    return pesticide, dosage, level


