def estimate_severity_bgr(img_bgr):
    img = cv2.resize(img_bgr, (512, 512))
    hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)

    # leaf green mask
    lower_green = np.array([25, 30, 30])
    upper_green = np.array([95, 255, 255])
    leaf_mask = cv2.inRange(hsv, lower_green, upper_green)

    leaf_pixels = np.sum(leaf_mask > 0)
    if leaf_pixels < 1000:
        leaf_mask = np.ones((512, 512), dtype=np.uint8) * 255
        leaf_pixels = 512 * 512

    # disease-ish mask (brown/yellow spots)
    lower_disease = np.array([5, 50, 50])
    upper_disease = np.array([35, 255, 255])
    disease_mask = cv2.inRange(hsv, lower_disease, upper_disease)

    disease_inside = cv2.bitwise_and(disease_mask, disease_mask, mask=leaf_mask)
    disease_pixels = np.sum(disease_inside > 0)

    severity = (disease_pixels / leaf_pixels) * 100.0
    return float(np.clip(severity, 0, 100))

def dosage_scale(base_dosage_ml_per_l, severity):
    if base_dosage_ml_per_l <= 0:
        return 0.0

    if severity < 5:
        factor = 0.5
    elif severity < 15:
        factor = 0.8
    elif severity < 35:
        factor = 1.0
    elif severity < 60:
        factor = 1.2
    else:
        factor = 1.4

    return round(base_dosage_ml_per_l * factor, 2)

